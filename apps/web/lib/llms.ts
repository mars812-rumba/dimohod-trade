export function validateLlmsPaths(paths: readonly string[] = llmsCanonicalPaths) {
  const seen = new Set<string>();

  for (const path of paths) {
    if (!path.startsWith("/") || path.includes("?") || path.includes("#")) {
      throw new Error(`llms.txt contains a non-canonical path: ${path}`);
    }
    if (seen.has(path)) {
      throw new Error(`llms.txt contains a duplicate path: ${path}`);
    }
    seen.add(path);
  }
}

function absoluteUrl(path: string, siteUrl: string, basePath: string) {
  return new URL(`${basePath}${path}`, siteUrl).toString();
}

