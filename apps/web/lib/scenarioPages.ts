export type ScenarioKind = "hub" | "object" | "heat_source";

export type ScenarioIconName =
  | "building"
  | "camera"
  | "file"
  | "flame"
  | "home"
  | "route"
  | "ruler"
  | "shield"
  | "wrench";

export type ScenarioInput = {
  title: string;
  description: string;
  icon: ScenarioIconName;
};

export type ScenarioRouteOption = {
  slug: string;
  title: string;
  description: string;
  image?: string;
  href?: string;
};

export type ScenarioQuestion = {
  title: string;
  description: string;
};

export type ScenarioRelatedGroup = {
  title: string;
  description: string;
  categorySlug?: string;
};

export type ScenarioFaqItem = {
  question: string;
  answer: string;
};

export type ScenarioMetadata = {
  title: string;
  description: string;
};

export type ScenarioPageContent = {
  slug: string;
  kind: ScenarioKind;
  eyebrow: string;
  title: string;
  summary: string;
  heroImage: string;
  heroImageAlt: string;
  requiredInputs: ScenarioInput[];
  routeOptions: ScenarioRouteOption[];
  routeSectionTitle?: string;
  routeSectionDescription?: string;
  selectionQuestions: ScenarioQuestion[];
  relatedGroups: ScenarioRelatedGroup[];
  technicalFactKeys: string[];
  faq: ScenarioFaqItem[];
  configuratorPreset: Record<string, string>;
  metadata: ScenarioMetadata;
};

export function scenarioConfiguratorHref(content: ScenarioPageContent): string {
  const params = new URLSearchParams(content.configuratorPreset);
  const query = params.toString();
  return query ? `/?${query}#calculator` : "/#calculator";
}

